#!/usr/bin/env python
"""Aggregate per-draw NGF CSVs -> ngf_all_methods.csv, ngf_summary.md, ngf_vs_dice_gain.png.
CPU-light (pandas/matplotlib); run via run_aggregate.sh (small Slurm CPU job), not on the login node."""
from __future__ import annotations

import re
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from scipy.stats import spearmanr

HERE = Path(__file__).resolve().parent
OUT = HERE.parent
DATA = OUT / "data"
DICE_MD = OUT.parent / "meta_task_heatmap_paper_summary.md"

# NGF method key -> Dice-table row index (order of the paper's Dice table)
DICE_ROWS = ["baseline", "synthseg_noEM", "synthseg_EM", "auglab_default", "srcsm", "ours_train050"]
LABEL = {"baseline": "baseline (nnU-Net default; = source ref)", "synthseg_noEM": "SynthSeg-noEM",
         "synthseg_EM": "SynthSeg-EM", "auglab_default": "Auglab", "srcsm": "SRCSM",
         "ours_train050": "PALETTE-Aug (Ours, train050)", "palette": "PALETTE alone (real fill)",
         "noisefill": "noise-fill (Voronoi, rung 4)", "kmeans_remap": "K-means+remap (noise fill, rung 3)",
         "kmeans": "K-means (noise fill, rung 2)", "identity": "source (identity)", "noise": "isotropic-noise floor"}
# task key (our) -> Dice-table column, appearance-defined?
TASKCOL = {"glioma": ("brats2024-glioma", True), "ms": ("open-ms", True), "breast": ("ispy2", True),
           "abdomen": ("chaos", False), "brain_healthy": ("on-harmony", False),
           "mandible": ("toothfairy2", False), "pelvis": ("totalseg-pelvic", False)}
TASK_ORDER = ["glioma", "ms", "breast", "abdomen", "brain_healthy", "mandible", "pelvis"]
MARK = dict(zip(TASK_ORDER, ["o", "s", "^", "D", "v", "P", "X"]))
METH_COL = {"synthseg_noEM": "#8c564b", "synthseg_EM": "#e377c2", "auglab_default": "#1f77b4",
            "srcsm": "#2ca02c", "ours_train050": "#d62728"}


def read_dice():
    lines = DICE_MD.read_text().splitlines()
    start = next(i for i, l in enumerate(lines) if l.startswith("## Dice"))
    end = next(i for i, l in enumerate(lines) if l.startswith("## HD95"))
    hdr = [c.strip() for c in lines[start + 2].strip("|").split("|")]
    rows = [l for l in lines[start + 4:end] if l.startswith("| **")][:6]
    dice = {}
    for name, l in zip(DICE_ROWS, rows):
        cells = [c.strip() for c in l.strip().strip("|").split("|")]
        vals = cells[1:]
        for col, v in zip(hdr[1:], vals):
            m = re.match(r"\**([0-9.]+)", v.replace("*", ""))
            dice[(name, col)] = float(m.group(1)) if m else np.nan
    return dice


def main(variant="noblur"):
    files = [f for f in sorted(DATA.glob("ngf_*.csv")) if "smoke" not in f.name and "verify" not in f.name]
    df = pd.concat([pd.read_csv(f) for f in files], ignore_index=True)
    df.to_csv(OUT / "ngf_per_draw.csv.gz", index=False)
    # reference rows have variant == "ref": replicate into every variant for convenience
    ref = df[df.variant == "ref"]
    outs = []
    for v in sorted(set(df.variant) - {"ref"}):
        outs.append(pd.concat([df[df.variant == v], ref.assign(variant=v)]))
    d = pd.concat(outs, ignore_index=True)
    # scan-level mean over draws
    sc = (d.groupby(["task", "dataset", "contrast", "variant", "roi", "method", "scan"])
            .agg(ngf_all=("ngf_all", "mean"), ngf_edge=("ngf_edge", "mean"), n_draws=("draw", "nunique"),
                 n_fail_free=("ngf_all", "count")).reset_index())
    g = sc.groupby(["task", "dataset", "contrast", "variant", "roi", "method"])
    summ = g.agg(ngf_mean=("ngf_all", "mean"), ngf_sd_across_scans=("ngf_all", "std"),
                 ngf_edge_mean=("ngf_edge", "mean"), n_scans=("scan", "nunique"),
                 n_draws=("n_draws", "max")).reset_index()
    sd_draw = (d.groupby(["task", "dataset", "contrast", "variant", "roi", "method"])["ngf_all"].std()
                 .rename("ngf_sd_all_draws").reset_index())
    summ = summ.merge(sd_draw, on=["task", "dataset", "contrast", "variant", "roi", "method"])
    summ.to_csv(OUT / "ngf_all_methods.csv", index=False)

    # task-level (equal weight per contrast)
    def tasklevel(variant, roi="fg", col="ngf_mean"):
        s = summ[(summ.variant == variant) & (summ.roi == roi)]
        t = s.groupby(["task", "dataset", "method"]).agg(v=(col, "mean"), n_contrasts=("contrast", "nunique"),
                                                          sd=("ngf_sd_across_scans", "mean")).reset_index()
        return t

    dice = read_dice()
    md = []
    md.append("# NGF texture preservation, all methods x all ablation tasks\n")
    md.append(f"Generated by `scripts/aggregate_ngf.py` from {len(files)} per-dataset CSVs "
              f"(`data/ngf_*.csv`; per-draw rows in `ngf_per_draw.csv.gz`, summary rows in `ngf_all_methods.csv`).\n")
    md.append(METHOD_NOTE)
    corr_rows = []
    pts = []
    for var in sorted(set(summ.variant)):
        t = tasklevel(var)
        tasks = [k for k in TASK_ORDER if k in set(t.task)]
        meths = ["identity", "palette", "noisefill", "kmeans_remap", "kmeans", "auglab_default", "synthseg_EM", "synthseg_noEM",
                 "srcsm", "ours_train050", "noise"]
        md.append(f"\n## Mean NGF per method x task  [variant = `{var}`, ROI = foreground eroded x3; mean over contrasts of the "
                  f"per-contrast mean over scans (each scan first averaged over draws); +- = mean over contrasts of the "
                  f"across-scan sd]\n")
        hdr = "| method | " + " | ".join(f"{TASKCOL[k][0]}{' (A)' if TASKCOL[k][1] else ' (I)'}" for k in tasks) + " | mean over tasks |"
        md.append(hdr); md.append("|---" * (len(tasks) + 2) + "|")
        for m in meths:
            cells, vals = [], []
            for k in tasks:
                r = t[(t.task == k) & (t.method == m)]
                if len(r):
                    cells.append(f"{r.v.iloc[0]:.3f} +- {r.sd.iloc[0]:.3f}"); vals.append(r.v.iloc[0])
                else:
                    cells.append("n/a")
            md.append(f"| {LABEL[m]} | " + " | ".join(cells) + f" | {np.mean(vals):.3f} |" if vals else f"| {LABEL[m]} | " + " | ".join(cells) + " | n/a |")
        md.append("\n(A) = appearance-defined target (glioma, MS, breast); (I) = interface-bounded target (abdomen, healthy brain, mandible, pelvis). "
                  "`baseline` = nnU-Net default pipeline: no appearance-synthesis, treated as the source reference (NGF 1 by construction; its mild "
                  "intensity augs are NOT simulated).\n")
        # per-contrast detail
        md.append(f"\n### Per-contrast detail [variant `{var}`]  (mean NGF; n scans)\n")
        s = summ[(summ.variant == var) & (summ.roi == "fg")]
        cons = s[["task", "dataset", "contrast"]].drop_duplicates()
        cons["o"] = cons.task.map({k: i for i, k in enumerate(TASK_ORDER)})
        cons = cons.sort_values(["o", "dataset", "contrast"])
        md.append("| dataset/contrast | n | " + " | ".join(LABEL[m].split(" (")[0] for m in meths) + " |")
        md.append("|---" * (len(meths) + 2) + "|")
        for _, r in cons.iterrows():
            ss = s[(s.dataset == r.dataset) & (s.contrast == r.contrast)]
            cells = []
            for m in meths:
                x = ss[ss.method == m]
                cells.append(f"{x.ngf_mean.iloc[0]:.3f}" if len(x) else "n/a")
            n = int(ss.n_scans.max()); dr = int(ss.n_draws.max())
            md.append(f"| {r.dataset}/{r.contrast} | {n}x{dr} | " + " | ".join(cells) + " |")
        # correlations
        for task in tasks:
            col, _ = TASKCOL[task]
            xs, ys, names = [], [], []
            for m in DICE_ROWS[1:]:
                r = t[(t.task == task) & (t.method == m)]
                if not len(r):
                    continue
                gain = dice[(m, col)] - dice[("baseline", col)]
                xs.append(r.v.iloc[0]); ys.append(gain); names.append(m)
                pts.append(dict(variant=var, task=task, method=m, ngf=r.v.iloc[0], gain=gain))
            if len(xs) >= 4:
                rho, p = spearmanr(xs, ys)
            else:
                rho, p = np.nan, np.nan
            # with baseline (identity, NGF=1, gain=0)
            rho_b, p_b = spearmanr(xs + [1.0], ys + [0.0]) if len(xs) >= 4 else (np.nan, np.nan)
            corr_rows.append(dict(variant=var, task=task, appearance=TASKCOL[task][1], n=len(xs), rho=rho, p=p,
                                  rho_with_baseline=rho_b, p_with_baseline=p_b))
    pts = pd.DataFrame(pts)
    pts.to_csv(OUT / "ngf_vs_dice_gain_points.csv", index=False)
    cr = pd.DataFrame(corr_rows)
    cr.to_csv(OUT / "ngf_dice_gain_spearman.csv", index=False)
    md.append("\n## Spearman correlation: NGF vs Dice gain over baseline, across the 5 methods per task\n")
    md.append("Methods: SynthSeg-noEM, SynthSeg-EM, Auglab, SRCSM, PALETTE-Aug (Ours); Dice gain = method Dice - baseline Dice from "
              "`meta_task_heatmap_paper_summary.md` (task-level `all` column). With only n=5 points per task the exact two-sided p-value "
              "can never go below 0.017 (|rho|=1) and a single swap changes rho by 0.2: read the sign/magnitude pattern, not the p-values. "
              "`with baseline` adds the baseline as a 6th point at (NGF 1, gain 0).\n")
    for var in sorted(set(cr.variant)):
        md.append(f"\n[variant `{var}`]\n")
        md.append("| task | type | n | rho | p | rho (with baseline) | p (with baseline) |"); md.append("|---|---|---|---|---|---|---|")
        for _, r in cr[cr.variant == var].iterrows():
            md.append(f"| {TASKCOL[r.task][0]} | {'appearance' if r.appearance else 'interface'} | {r.n} | {r.rho:.2f} | {r.p:.3f} | "
                      f"{r.rho_with_baseline:.2f} | {r.p_with_baseline:.3f} |")
        for lab, flag in (("appearance-defined tasks pooled", True), ("interface-bounded tasks pooled", False)):
            q = pts[(pts.variant == var) & pts.task.map(lambda k: TASKCOL[k][1] == flag)]
            if len(q) >= 4:
                # pooled with task-demeaned NGF and gain (within-task association)
                qx = q.ngf - q.groupby("task").ngf.transform("mean"); qy = q.gain - q.groupby("task").gain.transform("mean")
                rr, pp = spearmanr(qx, qy)
                r0, p0 = spearmanr(q.ngf, q.gain)
                md.append(f"\n{lab}: raw Spearman rho={r0:.2f} (p={p0:.3g}, n={len(q)}); task-demeaned (within-task) rho={rr:.2f} (p={pp:.3g}).")
    (OUT / "ngf_summary.md").write_text("\n".join(md) + "\n")

    # figure (primary variant)
    for var in sorted(set(pts.variant)):
        fig, axes = plt.subplots(1, 2, figsize=(13, 5.4), sharex=True, sharey=True)
        for ax, flag, title in ((axes[0], True, "Appearance-defined targets (glioma, MS, breast)"),
                                (axes[1], False, "Interface-bounded targets (abdomen, healthy brain, mandible, pelvis)")):
            for k in TASK_ORDER:
                if TASKCOL[k][1] != flag:
                    continue
                q = pts[(pts.variant == var) & (pts.task == k)]
                for _, r in q.iterrows():
                    ax.scatter(r.ngf, r.gain, c=METH_COL[r.method], marker=MARK[k], s=70, edgecolor="k", linewidth=0.6, zorder=3)
            ax.axhline(0, c="grey", lw=0.8, ls=":"); ax.set_title(title, fontsize=10)
            ax.set_xlabel("texture kept: mean NGF vs source (1 = fully kept, ~1/3 = noise floor)")
            ax.grid(alpha=0.25)
            # per-task rho text
            txt = []
            for k in TASK_ORDER:
                if TASKCOL[k][1] == flag:
                    r = cr[(cr.variant == var) & (cr.task == k)]
                    if len(r):
                        txt.append(f"{TASKCOL[k][0]}: rho={r.rho.iloc[0]:.2f}")
            ax.text(0.02, 0.98, "Spearman (5 methods)\n" + "\n".join(txt), transform=ax.transAxes, va="top", fontsize=8,
                    bbox=dict(fc="white", ec="0.7", alpha=0.85))
            from matplotlib.lines import Line2D
            ax.legend(handles=[Line2D([], [], marker=MARK[k], ls="", mfc="w", mec="k", label=TASKCOL[k][0])
                               for k in TASK_ORDER if TASKCOL[k][1] == flag], loc="lower right", fontsize=8, title="task (marker)")
        axes[0].set_ylabel("Dice gain over baseline (points)")
        fig.legend(handles=[Line2D([], [], marker="o", ls="", mfc=c, mec="k", label=LABEL[m]) for m, c in METH_COL.items()],
                   loc="upper center", ncol=5, fontsize=9, title="method (colour)", bbox_to_anchor=(0.5, 1.03))
        fig.suptitle(f"[draft] NGF texture kept vs Dice gain  (generation variant: {var})", y=1.10, fontsize=11)
        fig.tight_layout()
        fn = OUT / ("ngf_vs_dice_gain.png" if var == "noblur" else f"ngf_vs_dice_gain_{var}.png")
        fig.savefig(fn, dpi=170, bbox_inches="tight"); plt.close(fig)
    print("wrote", OUT / "ngf_summary.md")


METHOD_NOTE = """
## How the numbers were produced

* Script: `scripts/ngf_all_methods.py` (one registry key = one dataset/contrast, 1 L40S job each, `scripts/run_key.sh`), aggregated by
  `scripts/aggregate_ngf.py`; one command for everything: `bash scripts/run_all.sh`.
* **Scans**: fixed random subset of N training scans per dataset/contrast (`numpy.default_rng(0)`, sorted nnU-Net `imagesTr` cases with a label
  file; ToothFairy2 from its BIDS tree, which already is 0.6 mm iso with the 3-class labels). N = min(20, available) (N is in the per-contrast
  table as `n x draws`). **Draws**: 5 augmentation draws per scan per method (seed = f(scan index, method, draw), identical scans/draw indices across methods).
* **Augmented image**: AugLab GPU transform (`AugTransformsGPU`) built from the SAME JSON the trainings used (`sub-workspaces/auglab_workspace/
  AugLab/auglab/configs/`), fed whole-image z-scored source + the task's `labelsTr` map (exactly like the existing `generate_*_volumes.py`), with only
  spatial transforms (Flip/Affine/nnUNetSpatial) zeroed so the output stays voxel-aligned. Standalone convention of the existing Open-MS/On-Harmony NGF
  tables: `palette` = `VALsynthonly_ImageContrastV26_6_2GPUTransform` (p=1), `noisefill` = `VALsynthonly_..NoiseFillV2` (same partition, noise fill;
  ladder rung 4), `kmeans`/`kmeans_remap` = rungs 2/3 (noise fill), `auglab_default` = `default01-23`, `synthseg_noEM/EM` = the `default01-23_Synthseg(_EM)`
  JSON with the SynthSeg block only (p=1, the other intensity augs zeroed as in the existing derived configs), `srcsm` = `srcsm_semrandconv` (SemRandConv only,
  `num_labels` = #labels incl. background of the dataset), `ours_train050` = `default01-23_auglabAug_ImageContrastV26_6_2GPUTransform_train050` AS TRAINED
  (PALETTE p=0.5 stacked on the full default augmentation chain; so ~half of its draws are PALETTE draws and the other half Auglab-like).
  Variant `noblur` (primary, = the paper's existing NGF protocol): blur/resolution degradation off (PALETTE `blur_sigmas=[0]`, SynthSeg fixed 1 mm no blur,
  Auglab GaussianBlur/SimulateLowRes p=0) so the metric reflects the fill, not resolution loss. Variant `asblur`: the training blur settings kept.
* **NGF**: `compute_ngf_texture.ngf_map` of the project (Haber & Modersitzki squared cosine of the 3-D Sobel gradient directions of source vs augmented), mean over
  ROI voxels. Primary ROI `fg` = foreground (source > 0.1 x p99 for MR/CBCT; HU > -500 for CT) eroded 3x (strips the tissue-boundary shell, as in the paper);
  secondary ROI `lab` (label > 0, eroded 1x) is in the CSVs only. Edge-gated NGF (top-50% source-gradient voxels) is in the CSVs as `ngf_edge_mean`.
* **References**: `identity` (augmented == source) = 1 by construction; `noise` = iid uniform noise (isotropic floor, expected ~1/3).
"""

if __name__ == "__main__":
    main()
