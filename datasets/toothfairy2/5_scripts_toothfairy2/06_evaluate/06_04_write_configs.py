#!/usr/bin/env python3
"""
Generate toothfairy2's results configs from the RUN_IDs the TamIA packs actually
used.

WHY THIS IS A SCRIPT AND NOT A HAND-EDITED YAML
-----------------------------------------------
RUN_IDs here are timestamped at launch (toothfairy2_cbct_baseline_<TS>, ...), so the
configs cannot be written before the packs are submitted. Every other dataset in this
repo has these ids typed in by hand — which is how ispy2 ended up repeating the same
timestamp across a dozen lines, and how a stale RUN_ID (pointing at deleted
checkpoints) slipped through on mslesseg. The packs already persist their ids in
<PACK_DIR>/RUN_IDS.env precisely so they survive a resume; this reads those files and
emits the configs, so the ids in the configs are by construction the ids that trained.

The OURS val100 mirror is derived, not read: the DualVal trainer materializes it by
substituting "_val000_" -> "_val100_" in the primary RUN_ID, so that substitution is
the correct way to name it here too.

EMITS FOUR CONFIGS
  toothfairy2_cbct_01_results.yaml          in-domain only (own held-out CBCT)
  toothfairy2_cross_dataset_01_results.yaml IN-DOMAIN + hanseg CT  <-- THE HEADLINE
  toothfairy2_combined_01_results.yaml      same, in the `modalities:` shape the
                                            cross-dataset meta_task_heatmap consumes
  toothfairy2_cbct_ladder.yaml              the 7-rung causal-ablation ladder

The cross-dataset and combined configs are the important ones. toothfairy2 has ONE
training modality, so its own held-out set is entirely in-domain and an in-domain-only
table cannot show generalization at all — the OOD column comes from the hanseg source.
Both use the shared `sources:` list (aggregate_from_config.load_run_from_sources /
combined_modality_summary), the same mechanism chaos uses to fold amos+sliver07 into
its cross-dataset table. `in_domain_contrast: cbct` is what makes the OOD column
exclude the training modality.

⚠️ THE 6-METHOD SUITE IS SPLIT ACROSS TWO PACKS, and each pack's RUN_IDS.env
contains ids for ALL SIX methods regardless of which three it actually trained
(04_13 generates the full set before PACK_METHODS filters what gets recorded). So
reading one pack yields three ids that were never trained. --suite-pack-a supplies
baseline / auglab_default / synthseg_noEM and --suite-pack-b supplies synthseg_EM /
srcsm / OURS, which is how they were actually launched. Composing it here removes
the after-the-fact regex patch the orchestrator used to apply.

Usage:
  06_04_write_configs.py --suite-pack-a <DIR> --suite-pack-b <DIR> \
                         [--ladder-pack <DIR>] [--out-dir <DIR>]
  06_04_write_configs.py --suite-pack <DIR> ...        # legacy: all six from one pack
"""
from __future__ import annotations

import argparse
import os
from pathlib import Path

HERE = Path(__file__).resolve().parent


def read_env(pack: Path) -> dict[str, str]:
    f = pack / "RUN_IDS.env"
    if not f.exists():
        raise SystemExit(f"no RUN_IDS.env in {pack} — was the pack ever submitted?")
    out = {}
    for line in f.read_text().splitlines():
        line = line.strip()
        if line and "=" in line and not line.startswith("#"):
            k, v = line.split("=", 1)
            out[k.strip()] = v.strip()
    return out


# ⚠️ Every emitted path is ${PROJECT_ROOT}-relative, NEVER ${METRICS_ROOT}. Both are
# exported by env.sh, but METRICS_ROOT additionally points at SCRATCH on TamIA while
# aggregation runs on Vulcan against the repo copy — and if it is ever unset, the
# aggregators write into a directory literally named "${METRICS_ROOT}". That has already
# happened once in this repo (see CLAUDE.md's cleanup notes: a stray ${METRICS_ROOT}/
# holding 4 misfiled *_significance.md files) and the standing instruction is to fix the
# script that writes it, not just delete the directory.
HEADLINE = """# toothfairy2 — OWN-model, CBCT-trained headline methods, own held-out CBCT test
# cases (71 sealed cases; see 4_splits_toothfairy2/test_cases.json).
#
# ⚠️ THIS TABLE IS IN-DOMAIN ONLY. toothfairy2 has a single training modality, so
# unlike every other dataset here there is no second in-house contrast to provide the
# OOD column. The cross-modality generalization result — the one the paper cares
# about — lives in the hanseg tables (CBCT-trained models on head-and-neck CT and
# MR-T1). Read this table as the in-domain reference, not as the headline.
#
# GENERATED by 06_04_write_configs.py from the packs' own RUN_IDS.env — do not
# hand-edit; regenerate instead.
title: "ToothFairy2 own-model — CBCT-trained (6-method suite, in-domain held-out test)"
metrics_dir: "${PROJECT_ROOT}/datasets/toothfairy2/8_results_toothfairy2/02_metrics/toothfairy2_model/cbct"
output_prefix: "01_results"
in_domain_contrast: cbct

runs:
"""

LADDER = """# toothfairy2 — CBCT causal-ablation ladder, baseline-anchored.
# Rungs: baseline -> +kmeans -> +label-remap -> +Voronoi (NOISE fill)
#        -> v26_6_2 alone (REAL fill) -> +AugLab val000 -> +AugLab val100
# The 4->5 step (noise fill -> real fill, partition otherwise identical) is the
# one-variable test of whether texture preservation causally drives Dice. This
# dataset is a BOUNDARY-defined target, so the paper's prediction is a near-zero
# step here, in contrast to the large step on texture-defined targets.
#
# GENERATED by 06_04_write_configs.py — do not hand-edit.
title: "ToothFairy2 CBCT — causal-ablation ladder"
metrics_dir: "${PROJECT_ROOT}/datasets/toothfairy2/8_results_toothfairy2/02_metrics/toothfairy2_model/cbct"
output_dir: "${PROJECT_ROOT}/datasets/toothfairy2/8_results_toothfairy2/02_metrics/toothfairy2_model/cbct/ablations"
output_prefix: "ladder"
in_domain_contrast: cbct

runs:
"""


TF2_METRICS = "${PROJECT_ROOT}/datasets/toothfairy2/8_results_toothfairy2/02_metrics/toothfairy2_model/cbct"
HS_METRICS = "${PROJECT_ROOT}/datasets/hanseg/8_results_hanseg/02_metrics/toothfairy2_model/cbct"

CROSS_HEAD = """# toothfairy2 — CROSS-DATASET table: own held-out CBCT (in-domain) + hanseg
# head-and-neck CT (cross-MODALITY). THIS IS THE HEADLINE TABLE for this task.
#
# toothfairy2 trains on a single modality, so unlike every other dataset here there is
# no second in-house contrast to provide an OOD column — the generalization result is
# carried entirely by the hanseg source. `in_domain_contrast: cbct` makes the OOD
# column exclude the training modality, so the OOD figure is the hanseg CT column.
#
# hanseg scores the MANDIBLE ONLY: its single Bone_Mandible structure equals this
# dataset's mandible + lower_teeth union (see hanseg 05_20_merge_mandible_union.py).
# One-class overlap, same shape as chaos -> sliver07 (liver only).
#
# GENERATED by 06_04_write_configs.py — do not hand-edit; regenerate.
title: "ToothFairy2 CBCT models — cross-dataset (in-domain CBCT + hanseg CT)"
in_domain_contrast: cbct
output_prefix: "02_cross_dataset"
output_dir: "%s"
column_order: [cbct, hanseg_ct]

sources:
  - metrics_dir: "%s"
  - metrics_dir: "%s"
    column_prefix: "hanseg_"

runs:
""" % (TF2_METRICS, TF2_METRICS, HS_METRICS)

TF2_COMBINED = ("${PROJECT_ROOT}/datasets/toothfairy2/8_results_toothfairy2/"
                "02_metrics/toothfairy2_model/combined_contrasts")
TF2_UNION = ("${PROJECT_ROOT}/datasets/toothfairy2/8_results_toothfairy2/"
             "02_metrics/toothfairy2_model/cbct_union")

COMBINED_HEAD = """# toothfairy2 — `combined_contrasts` table, in the shape the cross-DATASET
# meta_task_heatmap consumes (scripts/evaluate/meta_task_heatmap.yaml).
#
# Every other dataset's combined config pools its TWO training modalities. toothfairy2
# has one, so `modalities:` holds a single entry whose `sources:` list pools the two
# TEST sources instead.
#
# ⚠️ USES THE MANDIBLE-UNION VIEW for every column (cbct_union + hanseg_ct +
# hanseg_mrt1). Decided 2026-09-08: everything in this task is evaluated on the common
# label. Mixing a 3-class in-domain macro with single-class OOD columns made this
# task's `all` — the exact number the meta-heatmap consumes as its column — an average
# of incommensurable quantities. Requires the union view (06_09_build_union_view.sh).
#
# GENERATED by 06_04_write_configs.py — do not hand-edit; regenerate.
title: "ToothFairy2 — combined (single training modality: CBCT), mandible union"
output_dir: "%s"
output_prefix: "01_results"
ref: auglabAug_v26_6_2_train050_val000
column_order: [cbct_union, hanseg_ct, hanseg_mrt1]

modalities:
  - name: cbct
    sources:
      - metrics_dir: "%s"
      - metrics_dir: "%s"
        column_prefix: "hanseg_"
    runs:
""" % (TF2_COMBINED, TF2_UNION, HS_METRICS)

UNION_HEAD = """# toothfairy2 — LABEL-CONSISTENT table. EVERY column scores the SAME structure:
# the mandible union (mandible + lower_teeth), which is exactly HaN-Seg's Bone_Mandible.
#
# USE THIS TABLE FOR ANY CROSS-MODALITY CLAIM. The other cross-dataset config mixes a
# 3-class in-domain macro with single-class OOD columns, so its in-domain->OOD drop
# conflates "harder modality" with "different structures scored". The 3-class table
# remains the characterisation of the full task, not the modality comparison.
#
# Requires the union view: bash 06_09_build_union_view.sh (which needs
# 06_08_eval_mandible_union.py to have been run on every run).
# GENERATED by 06_04_write_configs.py — do not hand-edit; regenerate.
title: "ToothFairy2 — label-consistent (mandible union) across CBCT, CT and MRI"
in_domain_contrast: cbct_union
output_prefix: "03_union"
output_dir: "%s"
column_order: [cbct_union, hanseg_ct, hanseg_mrt1]

sources:
  - metrics_dir: "%s"
  - metrics_dir: "%s"
    column_prefix: "hanseg_"

runs:
""" % (TF2_UNION, TF2_UNION, HS_METRICS)

METHOD_KEYS = [
    ("baseline", "BASELINE_RUN_ID"),
    ("auglab_default", "AUGLAB_DEFAULT_RUN_ID"),
    ("synthseg_noEM", "SYNTHSEG_NOEM_RUN_ID"),
    ("synthseg_EM", "SYNTHSEG_EM_RUN_ID"),
    ("srcsm", "SRCSM_RUN_ID"),
    ("auglabAug_v26_6_2_train050_val000", "OURS_RUN_ID"),
]


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--suite-pack", type=Path,
                    help="legacy single-pack mode: take all six methods from here")
    ap.add_argument("--suite-pack-a", type=Path,
                    help="pack that trained baseline / auglab_default / synthseg_noEM")
    ap.add_argument("--suite-pack-b", type=Path,
                    help="pack that trained synthseg_EM / srcsm / OURS")
    ap.add_argument("--ladder-pack", type=Path)
    ap.add_argument("--out-dir", type=Path, default=HERE / "configs")
    a = ap.parse_args()
    a.out_dir.mkdir(parents=True, exist_ok=True)

    FROM_A = ["BASELINE_RUN_ID", "AUGLAB_DEFAULT_RUN_ID", "SYNTHSEG_NOEM_RUN_ID"]
    FROM_B = ["SYNTHSEG_EM_RUN_ID", "SRCSM_RUN_ID", "OURS_RUN_ID"]
    order = FROM_A + FROM_B
    if a.suite_pack_a and a.suite_pack_b:
        ea, eb = read_env(a.suite_pack_a), read_env(a.suite_pack_b)
        suite = {**{k: ea[k] for k in FROM_A if k in ea},
                 **{k: eb[k] for k in FROM_B if k in eb}}
    elif a.suite_pack:
        suite = read_env(a.suite_pack)
    else:
        raise SystemExit("need --suite-pack-a + --suite-pack-b (or legacy --suite-pack)")
    missing = [k for k in order if k not in suite]
    if missing:
        raise SystemExit(f"suite pack RUN_IDS.env missing {missing}")

    p = a.out_dir / "toothfairy2_cbct_01_results.yaml"
    p.write_text(HEADLINE + "".join(f"  - {suite[k]}\n" for k in order))
    print(f"wrote {p}")

    # ── cross-dataset (headline) + combined (meta-heatmap) ────────────────────
    q = a.out_dir / "toothfairy2_cross_dataset_01_results.yaml"
    q.write_text(CROSS_HEAD + "".join(f"  - {suite[k]}\n" for k in order))
    print(f"wrote {q}")

    u = a.out_dir / "toothfairy2_union_01_results.yaml"
    u.write_text(UNION_HEAD + "".join(f"  - {suite[k]}\n" for k in order))
    print(f"wrote {u}")

    c = a.out_dir / "toothfairy2_combined_01_results.yaml"
    c.write_text(COMBINED_HEAD
                 + "".join(f"      {m}: {suite[k]}\n" for m, k in METHOD_KEYS))
    print(f"wrote {c}")

    if a.ladder_pack:
        lad = read_env(a.ladder_pack)
        ours = suite["OURS_RUN_ID"]
        if ours.count("_val000_") != 1:
            raise SystemExit(f"OURS RUN_ID {ours!r} must contain '_val000_' exactly once")
        rungs = [suite["BASELINE_RUN_ID"],
                 lad["R2_RUN_ID"], lad["R3_RUN_ID"], lad["R4_RUN_ID"], lad["R5_RUN_ID"],
                 ours, ours.replace("_val000_", "_val100_", 1)]
        q = a.out_dir / "toothfairy2_cbct_ladder.yaml"
        q.write_text(LADDER + "".join(f"  - {r}\n" for r in rungs))
        print(f"wrote {q}")


if __name__ == "__main__":
    main()
