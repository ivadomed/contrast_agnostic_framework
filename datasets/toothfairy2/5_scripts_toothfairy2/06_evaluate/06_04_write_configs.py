#!/usr/bin/env python3
"""
Generate toothfairy2's results configs from the RUN_IDs the TamIA packs actually
used.

WHY THIS IS A SCRIPT AND NOT A HAND-EDITED YAML
-----------------------------------------------
RUN_IDs here are timestamped at launch (toothfairy2_cbct_baseline_<TS>, ...), so the
configs cannot be written before the packs are submitted. Every other dataset in this
repo has these ids typed in by hand — which is how ispy2 ended up repeating the same
timestamp across a dozen lines, and how a stale RUN_ID (pointing at deleted
checkpoints) slipped through on mslesseg. The packs already persist their ids in
<PACK_DIR>/RUN_IDS.env precisely so they survive a resume; this reads those files and
emits the configs, so the ids in the configs are by construction the ids that trained.

The OURS val100 mirror is derived, not read: the DualVal trainer materializes it by
substituting "_val000_" -> "_val100_" in the primary RUN_ID, so that substitution is
the correct way to name it here too.

Usage:
  06_04_write_configs.py --suite-pack <DIR> [--ladder-pack <DIR>] [--out-dir <DIR>]
"""
from __future__ import annotations

import argparse
import os
from pathlib import Path

HERE = Path(__file__).resolve().parent


def read_env(pack: Path) -> dict[str, str]:
    f = pack / "RUN_IDS.env"
    if not f.exists():
        raise SystemExit(f"no RUN_IDS.env in {pack} — was the pack ever submitted?")
    out = {}
    for line in f.read_text().splitlines():
        line = line.strip()
        if line and "=" in line and not line.startswith("#"):
            k, v = line.split("=", 1)
            out[k.strip()] = v.strip()
    return out


HEADLINE = """# toothfairy2 — OWN-model, CBCT-trained headline methods, own held-out CBCT test
# cases (71 sealed cases; see 4_splits_toothfairy2/test_cases.json).
#
# ⚠️ THIS TABLE IS IN-DOMAIN ONLY. toothfairy2 has a single training modality, so
# unlike every other dataset here there is no second in-house contrast to provide the
# OOD column. The cross-modality generalization result — the one the paper cares
# about — lives in the hanseg tables (CBCT-trained models on head-and-neck CT and
# MR-T1). Read this table as the in-domain reference, not as the headline.
#
# GENERATED by 06_04_write_configs.py from the packs' own RUN_IDS.env — do not
# hand-edit; regenerate instead.
title: "ToothFairy2 own-model — CBCT-trained (6-method suite, in-domain held-out test)"
metrics_dir: "${METRICS_ROOT}/toothfairy2_model/cbct"
output_prefix: "01_results"
in_domain_contrast: cbct

runs:
"""

LADDER = """# toothfairy2 — CBCT causal-ablation ladder, baseline-anchored.
# Rungs: baseline -> +kmeans -> +label-remap -> +Voronoi (NOISE fill)
#        -> v26_6_2 alone (REAL fill) -> +AugLab val000 -> +AugLab val100
# The 4->5 step (noise fill -> real fill, partition otherwise identical) is the
# one-variable test of whether texture preservation causally drives Dice. This
# dataset is a BOUNDARY-defined target, so the paper's prediction is a near-zero
# step here, in contrast to the large step on texture-defined targets.
#
# GENERATED by 06_04_write_configs.py — do not hand-edit.
title: "ToothFairy2 CBCT — causal-ablation ladder"
metrics_dir: "${METRICS_ROOT}/toothfairy2_model/cbct"
output_dir: "${METRICS_ROOT}/toothfairy2_model/cbct/ablations"
output_prefix: "ladder"
in_domain_contrast: cbct

runs:
"""


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--suite-pack", required=True, type=Path)
    ap.add_argument("--ladder-pack", type=Path)
    ap.add_argument("--out-dir", type=Path, default=HERE / "configs")
    a = ap.parse_args()
    a.out_dir.mkdir(parents=True, exist_ok=True)

    suite = read_env(a.suite_pack)
    order = ["BASELINE_RUN_ID", "AUGLAB_DEFAULT_RUN_ID", "SYNTHSEG_NOEM_RUN_ID",
             "SYNTHSEG_EM_RUN_ID", "SRCSM_RUN_ID", "OURS_RUN_ID"]
    missing = [k for k in order if k not in suite]
    if missing:
        raise SystemExit(f"suite pack RUN_IDS.env missing {missing}")

    p = a.out_dir / "toothfairy2_cbct_01_results.yaml"
    p.write_text(HEADLINE + "".join(f"  - {suite[k]}\n" for k in order))
    print(f"wrote {p}")

    if a.ladder_pack:
        lad = read_env(a.ladder_pack)
        ours = suite["OURS_RUN_ID"]
        if ours.count("_val000_") != 1:
            raise SystemExit(f"OURS RUN_ID {ours!r} must contain '_val000_' exactly once")
        rungs = [suite["BASELINE_RUN_ID"],
                 lad["R2_RUN_ID"], lad["R3_RUN_ID"], lad["R4_RUN_ID"], lad["R5_RUN_ID"],
                 ours, ours.replace("_val000_", "_val100_", 1)]
        q = a.out_dir / "toothfairy2_cbct_ladder.yaml"
        q.write_text(LADDER + "".join(f"  - {r}\n" for r in rungs))
        print(f"wrote {q}")


if __name__ == "__main__":
    main()
