#!/usr/bin/env python3
"""Generate a dataset's standard aggregate / significance / combined YAML configs from the roster pin files, so no config
hardcodes a timestamp and every dataset's configs have the same shape. Consumed by the usual
06_02_aggregate_from_config.sh / 06_03_significance_from_config.sh / 06_04_combined_modality_summary.sh.

Writes into <5_scripts>/06_evaluate/configs/:
  <name>_<contrast>_01_results.yaml        per training contrast, 7-method headline table (aggregate_from_config.py)
  <name>_<contrast>_significance_01.yaml   same runs, paired significance (significance_from_config.py)
  <name>_combined_01_results.yaml          all training contrasts pooled, ref = OURS val000 (combined_modality_summary.py)
Refuses to overwrite an existing config unless --force (the previous one is moved to <file>.bak_<timestamp>).

  .venv/bin/python write_configs_from_roster.py --dataset-root <.../isles2022> --model-type isles2022_model \
      --contrasts dwi flair --items dwi adc flair [--skip-missing] [--force]
"""
from __future__ import annotations
import argparse, datetime, sys
from pathlib import Path
import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
from roster_runs import HEADLINE_METHODS, OURS, pin_path, read_pins  # noqa: E402


def _write(p: Path, text: str, force: bool):
    yaml.safe_load(text)  # must parse
    if p.exists():
        if not force:
            print(f"EXISTS (use --force): {p}"); return
        p.rename(p.with_name(p.name + f".bak_{datetime.datetime.now():%Y%m%d_%H%M%S}"))
    p.write_text(text); print("wrote", p)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dataset-root", required=True); ap.add_argument("--model-type", required=True)
    ap.add_argument("--contrasts", nargs="+", required=True, help="training contrasts, in table order")
    ap.add_argument("--items", nargs="+", required=True, help="test items (column order)")
    ap.add_argument("--skip-missing", action="store_true"); ap.add_argument("--force", action="store_true")
    a = ap.parse_args()
    root = Path(a.dataset_root).resolve(); name = root.name
    proj = next(p for p in root.parents if p.name == "benchmark").parent
    rel = root.relative_to(proj)
    res = "${PROJECT_ROOT}/" + str(rel / f"8_results_{name}" / "02_metrics" / a.model_type)
    cfg_dir = root / f"5_scripts_{name}" / "06_evaluate" / "configs"; cfg_dir.mkdir(parents=True, exist_ok=True)

    runs = {}
    for c in a.contrasts:
        pins = read_pins(pin_path(root, name, a.model_type, c))
        miss = [m for m in HEADLINE_METHODS if m not in pins]
        if miss and not a.skip_missing:
            sys.exit(f"[{c}] no pinned run for {miss}; predict them first or pass --skip-missing")
        runs[c] = {m: pins[m][1] for m in HEADLINE_METHODS if m in pins}
        order = [c] + [i for i in a.items if i != c]
        rl = "".join(f"  - {r}\n" for r in runs[c].values())
        _write(cfg_dir / f"{name}_{c}_01_results.yaml",
               f'# {name} -- {c}-trained headline methods, scored on every test item ({", ".join(a.items)}).\n'
               f'# GENERATED by 00_03_evaluate/write_configs_from_roster.py from roster_run_ids.tsv -- do not hand-edit run ids.\n'
               f'title: "{name} own-model -- {c.upper()}-trained"\nmetrics_dir: "{res}/{c}"\noutput_prefix: "01_results"\n'
               f'in_domain_contrast: {c}\ncolumn_order: [{", ".join(order)}]\n\nruns:\n{rl}', a.force)
        _write(cfg_dir / f"{name}_{c}_significance_01.yaml",
               f'# {name} {c}-TRAINED -- paired significance (significance_from_config.py), OOD = every non-training item.\n'
               f'# GENERATED by write_configs_from_roster.py.\n'
               f'title: "{name} {c.upper()}-TRAINED -- significance"\nin_domain_contrast: {c}\noutput_prefix: "01_results"\n'
               f'output_dir: "{res}/{c}"\ncolumn_order: [{", ".join(order)}]\n\nsources:\n  - metrics_dir: "{res}/{c}"\n\nruns:\n{rl}', a.force)

    mods = ""
    for c in a.contrasts:
        mods += f"  - name: {c}\n    metrics_dir: \"{res}/{c}\"\n    runs:\n"
        mods += "".join(f"      {m}: {r}\n" for m, r in runs[c].items())
    _write(cfg_dir / f"{name}_combined_01_results.yaml",
           f'# {name} -- all training contrasts pooled, cross-contrast (combined_modality_summary.py).\n'
           f'# GENERATED by write_configs_from_roster.py from roster_run_ids.tsv.\n'
           f'title: "{name} -- combined training contrasts ({" + ".join(a.contrasts)}), cross-contrast"\n'
           f'output_dir: "{res}/combined_contrasts"\noutput_prefix: "01_results"\nref: {OURS}\n'
           f'column_order: [{", ".join(a.items)}]\n\nmodalities:\n{mods}', a.force)


if __name__ == "__main__":
    main()
