#!/usr/bin/env python3
"""Generate an EVAL-ONLY COMPANION's aggregate + combined YAML configs from the SOURCE task's roster pins (no timestamps, same shape for every companion).
Companion metrics layout: <companion>/8_results_<c>/02_metrics/<model_type>/<source contrast>/<item>/<category>_<RUN_ID>/fold*/eval_all.csv.

Writes into <companion>/5_scripts_<c>/06_evaluate/configs/:
  <c>_<item>_<contrast>_01_results.yaml   one per (test item, source training contrast): headline table for that arm (aggregate_from_config.py)
  <c>_combined_01_results.yaml            all source contrasts pooled, columns = items (combined_modality_summary.py), ref = OURS val000
These are the companion's OWN tables. Wiring the companion into the SOURCE task's combined table / ladders (pool by TRUE contrast; a same-contrast item is
cross-dataset only, never OOD) is a separate, deliberate edit -- see the skill. Existing files are kept unless --force (old one moved to .bak_<ts>).

  .venv/bin/python write_companion_configs_from_roster.py --companion-root <.../ispy1> --source-root <.../ispy2> --model-type ispy2_model --contrasts t1wce t2w --items t1wce precontrast
"""
from __future__ import annotations
import argparse, datetime, sys
from pathlib import Path
import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
from roster_runs import HEADLINE_METHODS, OURS, pin_path, read_pins  # noqa: E402


def _write(p: Path, text: str, force: bool):
    yaml.safe_load(text)
    if p.exists():
        if not force:
            print(f"EXISTS (use --force): {p}"); return
        p.rename(p.with_name(p.name + f".bak_{datetime.datetime.now():%Y%m%d_%H%M%S}"))
    p.write_text(text); print("wrote", p)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--companion-root", required=True); ap.add_argument("--source-root", required=True); ap.add_argument("--model-type", required=True)
    ap.add_argument("--contrasts", nargs="+", required=True); ap.add_argument("--items", nargs="+", required=True)
    ap.add_argument("--skip-missing", action="store_true"); ap.add_argument("--force", action="store_true")
    a = ap.parse_args()
    comp = Path(a.companion_root).resolve(); cname = comp.name; src = Path(a.source_root).resolve(); sname = src.name
    proj = next(p for p in comp.parents if p.name == "benchmark").parent
    res = "${PROJECT_ROOT}/" + str(comp.relative_to(proj) / f"8_results_{cname}" / "02_metrics" / a.model_type)
    cfg = comp / f"5_scripts_{cname}" / "06_evaluate" / "configs"; cfg.mkdir(parents=True, exist_ok=True)
    runs = {}
    for c in a.contrasts:
        pins = read_pins(pin_path(src, sname, a.model_type, c))
        miss = [m for m in HEADLINE_METHODS if m not in pins]
        if miss and not a.skip_missing:
            sys.exit(f"[source {c}] no pinned run for {miss} (source roster incomplete); --skip-missing to proceed without them")
        runs[c] = {m: pins[m][1] for m in HEADLINE_METHODS if m in pins}
        for it in a.items:
            rl = "".join(f"  - {r}\n" for r in runs[c].values())
            _write(cfg / f"{cname}_{it}_{c}_01_results.yaml",
                   f'# {cname} -- test item {it}, scored with the {sname} {c}-TRAINED models. GENERATED by write_companion_configs_from_roster.py from the source roster pins.\n'
                   f'title: "{cname} {it} -- {sname.upper()} {c.upper()}-trained models"\nmetrics_dir: "{res}/{c}/{it}"\noutput_prefix: "01_results"\n'
                   f'sig_ref: "{runs[c].get(OURS, "")}"\n\nruns:\n{rl}', a.force)
    mods = ""
    for c in a.contrasts:
        mods += f"  - name: {c}\n    sources:\n" + "".join(f'      - metrics_dir: "{res}/{c}/{it}"\n' for it in a.items)
        mods += "    runs:\n" + "".join(f"      {m}: {r}\n" for m, r in runs[c].items())
    _write(cfg / f"{cname}_combined_01_results.yaml",
           f'# {cname} -- all {sname} training contrasts pooled, per-item columns (combined_modality_summary.py). GENERATED from the source roster pins.\n'
           f'title: "{cname} -- combined {sname.upper()}-trained contrasts ({" + ".join(a.contrasts)}), cross-dataset"\n'
           f'output_dir: "{res}/combined_contrasts"\noutput_prefix: "01_results"\nref: {OURS}\ncolumn_order: [{", ".join(a.items)}]\n\nmodalities:\n{mods}', a.force)


if __name__ == "__main__":
    main()
